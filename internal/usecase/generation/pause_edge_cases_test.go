package generation

import (
	"fmt"
	"testing"
)

func TestConvertPauseMarkers_EdgeCases(t *testing.T) {
	cases := []struct {
		name  string
		input string
	}{
		// ── 各种点号组合 ──
		{"1个英文点 .", "你好.我是vidu"},
		{"2个英文点 ..", "你好..我是vidu"},
		{"3个英文点 ...", "你好...我是vidu"},
		{"4个英文点 ....", "你好....我是vidu"},
		{"5个英文点 .....", "你好.....我是vidu"},
		{"1个中文句号 。", "你好。我是vidu"},
		{"2个中文句号 。。", "你好。。我是vidu"},
		{"3个中文句号 。。。", "你好。。。我是vidu"},
		{"4个中文句号 。。。。", "你好。。。。我是vidu"},

		// ── 中英混合点号 ──
		{"中文+英文 。.", "你好。.我是vidu"},
		{"英文+中文 .。", "你好.。我是vidu"},
		{"混合 。..", "你好。..我是vidu"},
		{"混合 ..。", "你好..。我是vidu"},

		// ── 各种问号叹号组合 ──
		{"1个问号 ?", "你好?我是vidu"},
		{"2个问号 ??", "你好??我是vidu"},
		{"1个叹号 !", "你好!我是vidu"},
		{"2个叹号 !!", "你好!!我是vidu"},
		{"问号+叹号 !?", "你好!?我是vidu"},
		{"叹号+问号 ?!", "你好?!我是vidu"},
		{"中文问+叹 ？！", "你好？！我是vidu"},
		{"中文叹+问 ！？", "你好！？我是vidu"},

		// ── 各种逗号组合 ──
		{"1个逗号 ,", "你好,我是vidu"},
		{"2个逗号 ,,", "你好,,我是vidu"},
		{"1个顿号 、", "你好、我是vidu"},
		{"2个顿号 、、", "你好、、我是vidu"},
		{"逗号+顿号 ,、", "你好,、我是vidu"},

		// ── 混合标点 ──
		{"句号+逗号 。,", "你好。,我是vidu"},
		{"逗号+句号 ,。", "你好,。我是vidu"},
		{"省略号+问号 ...?", "你好...?我是vidu"},
		{"省略号+叹号 ...!", "你好...!我是vidu"},
		{"问号+省略号 ?...", "你好?...我是vidu"},
		{"中文省略号+问号 。。。？", "你好。。。？我是vidu"},

		// ── 空白和特殊字符 ──
		{"纯空格", "你好 我是vidu"},
		{"纯制表符", "你好\t我是vidu"},
		{"多个换行\n\n", "你好\n\n我是vidu"},
		{"换行+逗号 \n,", "你好\n,我是vidu"},

		// ── 极端情况 ──
		{"全是标点", "，。！？...、、；"},
		{"标点开头", "，你好"},
		{"标点结尾", "你好，"},
		{"连续不同标点", "，。！？"},
		{"10个点", "你好..........我是vidu"},
	}

	fmt.Println()
	fmt.Println("╔══════════════════════════════════════════════════════════════════════════════════╗")
	fmt.Println("║                    停顿转换 · 边界情况测试                                      ║")
	fmt.Println("╚══════════════════════════════════════════════════════════════════════════════════╝")
	fmt.Println()

	for _, c := range cases {
		got := convertPauseMarkers(c.input)
		t.Run(c.name, func(t *testing.T) {})

		status := "✅"
		if got == c.input {
			status = "⚪"
		}

		fmt.Printf("  %s %-25s\n", status, c.name)
		fmt.Printf("     输入: %q\n", c.input)
		fmt.Printf("     输出: %q\n", got)
		fmt.Println()
	}
}
