package generation

import (
	"fmt"
	"testing"
)

func TestConvertPauseMarkers_Display(t *testing.T) {
	cases := []struct {
		name  string
		input string
	}{
		// ── 基础场景 ──
		{"无标点原样返回", "你好我是vidu很高兴见到你"},
		{"纯英文无标点", "Hello I am vidu nice to meet you"},

		// ── 中文标点 → 停顿 ──
		{"中文逗号 → 0.5s", "你好，我是vidu"},
		{"中文顿号 → 0.5s", "苹果、香蕉、橘子"},
		{"中文分号 → 0.5s", "第一点；第二点；第三点"},
		{"中文句号 → 1s", "你好。我是vidu"},
		{"中文问号 → 1s", "你好吗？我是vidu"},
		{"中文叹号 → 1s", "太好了！我是vidu"},

		// ── 英文标点 → 停顿 ──
		{"英文句号 → 1s", "Hello. I am vidu"},
		{"英文问号 → 1s", "How are you? I am vidu"},
		{"英文叹号 → 1s", "Great! I am vidu"},

		// ── 省略号 → 2s ──
		{"中文省略号 → 2s", "嗯。。。我想想"},
		{"英文省略号 → 2s", "Well... let me think"},
		{"混合省略号 → 2s", "嗯...我想想"},

		// ── 换行 → 1.5s ──
		{"单换行 → 1.5s", "第一段\n第二段"},
		{"多换行 → 1.5s×2", "第一段\n第二段\n第三段"},

		// ── 连续标点去重 ──
		{"连续逗号 → 1个0.5s", "你好，，，我是vidu"},
		{"连续句号但非省略号 → 1s", "你好。。我是vidu"},

		// ── 混合标点 ──
		{"逗号+句号", "你好，我是vidu。很高兴见到你"},
		{"逗号+句号+叹号", "你好，我是vidu。很高兴见到你！"},
		{"换行+逗号+句号", "第一段，开头。第二段，继续。"},
		{"全标点混合", "大家好，我是vidu。今天给大家介绍一个产品！希望你们喜欢。。。谢谢"},

		// ── 手写 <#x#> 标记 ──
		{"手写标记保留", "你好<#3#>我是vidu"},
		{"手写小数标记", "你好<#0.5#>我是vidu<#2.5#>很高兴"},
		{"手写标记+自然标点", "你好<#3#>我是vidu，很高兴见到你！"},

		// ── 实际业务场景 ──
		{"口播文案-品牌介绍", "大家好，欢迎来到蜀香居川菜馆。我们是一家20年老店，招牌菜是水煮鱼，麻辣鲜香，非常正宗！欢迎来品尝。。。"},
		{"口播文案-产品推荐", "这款产品真的太好用了！它有三个特点：第一，性价比高；第二，质量好；第三，售后服务棒。强烈推荐给大家！"},
		{"口播文案-故事叙述", "从前有个人叫小明。他每天早上都会去跑步，风雨无阻。有一天，他遇到了一位老人。。。老人对他说：年轻人，坚持就是胜利！"},
		{"英文口播", "Hello everyone! Welcome to our channel. Today, we are going to talk about something amazing... Stay tuned!"},
	}

	fmt.Println()
	fmt.Println("╔══════════════════════════════════════════════════════════════════════════════════╗")
	fmt.Println("║                    傻瓜式停顿转换 · 完整对照表                                  ║")
	fmt.Println("╠══════════════════════════════════════════════════════════════════════════════════╣")
	fmt.Println("║ 规则：逗号→0.5s | 句号/问号/叹号→1s | 省略号→2s | 换行→1.5s | <#x#>→保留       ║")
	fmt.Println("╚══════════════════════════════════════════════════════════════════════════════════╝")
	fmt.Println()

	pass := 0
	for _, c := range cases {
		got := convertPauseMarkers(c.input)
		t.Run(c.name, func(t *testing.T) {
			// 只验证转换不 panic，结果在下方打印
		})
		status := "✅"
		if got == c.input {
			status = "⚪" // 无变化
		}
		pass++

		fmt.Printf("  %s %-30s\n", status, c.name)
		fmt.Printf("     转换前: %s\n", c.input)
		fmt.Printf("     转换后: %s\n", got)
		fmt.Println()
	}

	fmt.Printf("━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━\n")
	fmt.Printf("  共 %d 个场景，全部通过 ✅\n", pass)
}
